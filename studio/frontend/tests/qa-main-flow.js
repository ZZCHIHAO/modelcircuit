async (page) => {
  const notes = [];
  const check = (value, message) => { if (!value) throw new Error(message); notes.push(message); };
  const screenshotRoot = '../../output/playwright/';
  await page.getByRole('button', {name:'模型',exact:true}).click();
  await page.getByText('结构有效', {exact:true}).waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.react-flow__node').length === 8);
  check(await page.locator('.react-flow__node').count() === 8, 'Root graph renders two inputs, four calls and two outputs');
  await page.getByRole('button', {name:'encode_b · 内部结构',exact:true}).click();
  await page.locator('.react-flow__node[data-id="call:project"]').click();
  await page.getByRole('button', {name:'探针数据',exact:true}).click();
  await page.locator('.probe-sidebar code').filter({hasText:'call:encode_b/call:project'}).waitFor();
  check((await page.locator('.probe-metadata').innerText()).includes('16'), 'Nested probe comes from the selected encode_b call');
  await page.screenshot({path:screenshotRoot+'studio-chip-measured.png',scale:'css'});

  await page.getByRole('button', {name:'共享编码器 ×2',exact:true}).click();
  const hidden = page.getByRole('spinbutton', {name:'特征维度 hidden_features',exact:true});
  await hidden.fill('12');
  await hidden.press('Tab');
  await page.locator('.error-state').waitFor();
  check(await page.getByText(/结果已过期/).count() > 0, 'Semantic parameter edits invalidate previous measurements');
  await hidden.fill('8');
  await hidden.press('Tab');
  await page.getByText('结构有效', {exact:true}).waitFor();

  await page.getByRole('button', {name:'Python',exact:true}).click();
  const dialog = page.getByRole('dialog', {name:'Python 与画布'});
  const code = dialog.getByRole('textbox', {name:'Python 模型代码'});
  await code.waitFor();
  await page.waitForFunction(() => { const field=document.querySelector('textarea[aria-label="Python 模型代码"]'); return field && !field.readOnly && field.value.includes('class Model'); });
  const original = await code.inputValue();
  const invalid = original + '\nraise RuntimeError("must_not_execute")\n';
  await code.fill(invalid);
  await dialog.getByRole('button', {name:'重新解析到画布',exact:true}).click();
  await dialog.locator('.python-error').waitFor();
  await dialog.getByRole('button', {name:'关闭',exact:true}).click();
  await page.getByRole('button', {name:'Python',exact:true}).click();
  check(await code.inputValue() === invalid, 'Failed Python import preserves the draft when the editor is reopened');
  await dialog.getByRole('button', {name:'从画布重新生成',exact:true}).click();
  await dialog.getByRole('button', {name:'替换并重新生成',exact:true}).click();
  await page.waitForFunction(() => { const field=document.querySelector('textarea[aria-label="Python 模型代码"]'); return field && !field.readOnly && !field.value.includes('must_not_execute'); });
  let edited = await code.inputValue();
  check(edited.includes('hidden_features=8') && edited.includes('nn.Linear(in_features=8, out_features=2)'), 'Export contains readable chip construction and classification head');
  edited=edited.replaceAll('hidden_features=8','hidden_features=10').replace('nn.Linear(in_features=8, out_features=2)','nn.Linear(in_features=10, out_features=2)');
  await code.fill(edited);
  await dialog.getByRole('button', {name:'重新解析到画布',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  await page.getByText('结构有效', {exact:true}).waitFor();
  await page.getByRole('button', {name:'共享编码器 ×2',exact:true}).click();
  check(await page.getByRole('spinbutton', {name:'特征维度 hidden_features',exact:true}).inputValue() === '10', 'Source parameter changes are reflected in the visual graph');

  const jsonDownload=page.waitForEvent('download');
  await page.getByRole('button', {name:'保存项目 JSON',exact:true}).click();
  await (await jsonDownload).saveAs(screenshotRoot+'studio-edited-project.json');
  await page.getByRole('button', {name:'Python',exact:true}).click();
  await dialog.getByRole('button', {name:'从画布重新生成',exact:true}).click();
  await page.waitForFunction(() => { const field=document.querySelector('textarea[aria-label="Python 模型代码"]'); return field && !field.readOnly; });
  const pyDownload=page.waitForEvent('download');
  await dialog.getByRole('button', {name:'导出 .py',exact:true}).click();
  await (await pyDownload).saveAs(screenshotRoot+'studio-edited-model.py');
  await dialog.getByRole('button', {name:'关闭',exact:true}).click();
  notes.push('Project JSON and standalone Python were downloaded through the UI');

  await page.locator('.react-flow__node[data-id="call:encode_a"]').click();
  await page.locator('.react-flow__node[data-id="call:encode_b"]').click({modifiers:['Shift']});
  await page.locator('.react-flow__node[data-id="call:fuse"]').click({modifiers:['Shift']});
  await page.getByRole('button', {name:'封装',exact:true}).click();
  const chipDialog=page.getByRole('dialog', {name:'封装所选调用'});
  await chipDialog.getByRole('textbox', {name:'芯片名称',exact:true}).fill('双路融合芯片');
  await chipDialog.getByRole('textbox', {name:'芯片定义 ID',exact:true}).fill('paired_encoder_chip');
  await chipDialog.getByRole('combobox').selectOption('fuse');
  await chipDialog.getByRole('button', {name:'保存并新增实例',exact:true}).click();
  await chipDialog.waitFor({state:'hidden'});
  await page.getByText('结构有效', {exact:true}).waitFor();
  check(await page.getByRole('button', {name:'双路融合芯片 0.1.0 · 参数可绑定',exact:true}).count() === 1, 'Selected calls are packaged into a reusable chip definition');
  await page.getByRole('button', {name:'进入芯片内部',exact:true}).click();
  await page.waitForFunction(() => document.querySelectorAll('.react-flow__node').length === 6);
  check(await page.locator('.react-flow__node').count() === 6, 'New chip opens with its inferred boundary and selected internal calls');
  await page.screenshot({path:screenshotRoot+'studio-custom-chip.png',scale:'css'});
  return notes;
}
