async (page) => {
  const notes=[];
  await page.getByRole('button',{name:'模型',exact:true}).click();
  const node=page.locator('.react-flow__node[data-id="call:relu"]');
  if (!(await node.count())) await page.getByRole('button',{name:'ReLU ReLU 激活',exact:true}).click();
  await node.waitFor();
  await page.locator('.error-state').waitFor();
  const source=page.locator('.react-flow__node[data-id="call:fuse"] .react-flow__handle.source');
  const target=node.locator('.react-flow__handle.target');
  await source.scrollIntoViewIfNeeded();
  const a=await source.boundingBox(),b=await target.boundingBox();
  if(!a||!b)throw new Error('Connection handles unavailable');
  await page.mouse.move(a.x+a.width/2,a.y+a.height/2);
  await page.mouse.down();
  await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:15});
  await page.mouse.up();
  await page.getByText('结构有效',{exact:true}).waitFor();
  await node.click();
  if(await page.getByRole('combobox',{name:'x tensor',exact:true}).inputValue()!=='call:fuse')throw new Error('Drag connection did not update the named input');
  notes.push('Dragging source and target handles creates a validated named input connection');
  const before=await node.getAttribute('style');
  const title=node.locator('.node-name');
  const box=await title.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width/2+60,box.y+box.height/2-45,{steps:12});
  await page.mouse.up();
  if(await node.getAttribute('style')===before)throw new Error('Node dragging did not move the node');
  notes.push('Dragging the node updates its canvas position');
  await page.getByRole('button',{name:'删除此调用',exact:true}).click();
  await node.waitFor({state:'detached'});
  await page.getByText('结构有效',{exact:true}).waitFor();
  notes.push('Deleting the added call removes it and its incoming connection');
  await page.getByRole('button',{name:'载入双路分类器示例',exact:true}).click();
  await page.getByRole('button',{name:'encode_b · 内部结构',exact:true}).click();
  await page.locator('.react-flow__node[data-id="call:project"]').click();
  await page.getByRole('button',{name:'探针数据',exact:true}).click();
  await page.locator('.probe-sidebar code').filter({hasText:'call:encode_b/call:project'}).waitFor();
  return notes;
}
